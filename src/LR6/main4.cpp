#include "Stroka4.h"
#include <iostream>
using namespace std;

int main() {
    cout << "=== Тестирование класса Stroka ===\n" << endl;
    
    // Тестирование различных конструкторов
    cout << "1. Создание объектов разными конструкторами:" << endl;
    
    Stroka s1;                    // Конструктор по умолчанию
    Stroka s2("Привет, мир!");    // Конструктор из C-строки
    Stroka s3(s2);                 // Конструктор копирования
    Stroka s4(50);                 // НОВЫЙ конструктор с размером 50
    
    cout << "\n2. Вывод строк:" << endl;
    cout << "s1: "; s1.vyvod(); cout << " (пустая строка)" << endl;
    cout << "s2: "; s2.vyvod(); cout << endl;
    cout << "s3 (копия s2): "; s3.vyvod(); cout << endl;
    cout << "s4 (размер 50): "; s4.vyvod(); cout << " (пустая строка с выделенной памятью)" << endl;
    
    // Демонстрация работы с конструктором размера
    cout << "\n3. Работа со строкой, созданной через конструктор размера:" << endl;
    Stroka s5(100);  // Создаем строку с буфером на 100 символов
    
    cout << "Введите строку для s5 (макс. 100 символов): ";
    s5.vvod();
    
    cout << "s5 = ";
    s5.vyvod();
    cout << ", длина = " << s5.dlina() << endl;
    
    // Проверка автоматического вызова деструкторов
    cout << "\n4. Завершение программы - вызов деструкторов:" << endl;
    
    return 0;
}